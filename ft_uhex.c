#include "ft_printf.h"

int	ft_uhex(unsigned int n, int fd)
{
	char	*hex;

	hex = "0123456789ABCDEF";
	if (n >= 16)
		ft_uhex(n / 16, fd);
	ft_putchar_fd(hex[n % 16], fd);
	return (0);
}
